        public static InMemoryFileSystem CreateFileSystem()
        {
            var fs = new InMemoryFileSystem();
            Populate(fs);
            return fs;
        }

        /// <summary>ノート本文と、打った文字の来歴(履歴の 1 行)を fs に置く。</summary>
        public static void Populate(IFileSystem fs)
        {
            if (fs == null) throw new ArgumentNullException(nameof(fs));
            var paths = new ProjectPaths(Root);
            var history = new HistoryStore(fs, paths);
            fs.CreateDirectory(paths.NotesDir);
            foreach (var note in Notes)
            {
                var path = NotePath.Parse(note.Path);
                fs.WriteAllTextAtomic(paths.NoteFile(path), note.Text);
                if (!note.Typed) continue;
                history.AppendEvents(path, new[]
                {
                    new EditEvent { Seq = 1, T = 1, Type = EventType.Insert, Pos = 0, Text = note.Text, Len = note.Text.Length, Src = EventSource.Key },
                });
            }
        }
